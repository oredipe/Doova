#!/usr/bin/env bash
# Joins every migration into supabase/setup.sql, so a brand-new Supabase project can be set
# up by pasting one file into the SQL Editor. Run after changing any migration.
set -euo pipefail
cd "$(dirname "$0")"
{
  echo "-- Doova database setup: every migration in order. Generated by supabase/bundle.sh; do not edit by hand."
  echo "-- Paste into Supabase → SQL Editor → New query, then Run. Run it once, on an empty project."
  for f in migrations/*.sql; do echo; echo "-- ===== $(basename "$f") ====="; cat "$f"; done
} > setup.sql
echo "wrote supabase/setup.sql ($(wc -l < setup.sql) lines)"
